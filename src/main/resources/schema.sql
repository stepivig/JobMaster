CREATE TABLE IF NOT EXISTS JOBS
(
    ID                       BIGINT AUTO_INCREMENT PRIMARY KEY,
    NAME                     VARCHAR(30)  NOT NULL,
    DESCRIPTION              VARCHAR(500) NOT NULL,
    MEMORY_SIZE              INT          NOT NULL CHECK (MEMORY_SIZE > 0),
    RUNTIME                  VARCHAR(20)  NOT NULL CHECK (RUNTIME IN ('JAVA', 'KOTLIN')),
    TIMEOUT                  BIGINT       NOT NULL CHECK (TIMEOUT > 0),
    ACTIVE                   BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Code details
    CODE_TYPE                VARCHAR(20)  NOT NULL CHECK (CODE_TYPE IN ('RAW')),
    CODE_RAW                 CLOB,
    CODE_INPUT               CLOB,
    -- Schedule details
    SCHEDULE_TYPE            VARCHAR(9)   NOT NULL CHECK (SCHEDULE_TYPE IN ('ONCE', 'CRON')),
    SCHEDULE_CRON_EXPRESSION VARCHAR(106),
    CREATED_AT               TIMESTAMP             DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT               TIMESTAMP             DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS EXECUTIONS
(
    ID            BIGINT AUTO_INCREMENT PRIMARY KEY,
    JOB_ID        BIGINT      NOT NULL,
    STATUS        VARCHAR(30) NOT NULL,
    CREATION_TIME TIMESTAMP   NOT NULL,
    START_TIME    TIMESTAMP,
    END_TIME      TIMESTAMP,
    CUSTOM_INPUT  CLOB,
    OUTPUT        CLOB,
    FOREIGN KEY (JOB_ID) REFERENCES JOBS (ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_exec_status ON EXECUTIONS (STATUS);